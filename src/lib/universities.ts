export function searchUniversities(query: string): string[] {
    if (!query) return indianUniversities.slice(0, 50);
    
    const lowerQuery = query.toLowerCase().trim();
    
    return indianUniversities.filter(u => {
        const lowerU = u.toLowerCase();
        
        // Exact match or partial match on the full university string
        if (lowerU.includes(lowerQuery)) return true;
        
        // Advanced checking for acronyms and aliases
        for (const [abbr, expansions] of Object.entries(aliases)) {
            if (lowerQuery.includes(abbr)) {
                // If user types 'iit bombay', test all expansions
                for (const expansion of expansions) {
                    const expanded = lowerQuery.replace(new RegExp('\\\\b' + abbr + '\\\\b', 'g'), expansion);
                    if (expanded !== lowerQuery && lowerU.includes(expanded)) {
                        return true;
                    }
                }
            }
        }
        return false;
    }).slice(0, 50);
}
